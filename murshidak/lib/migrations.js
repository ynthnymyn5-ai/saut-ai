// Versioned schema/data changes, applied once per database (recorded in schema_migrations).
// They run inside the same locked transaction as table creation and seeding, so concurrent
// serverless cold starts apply each migration exactly once. Never edit a migration that has
// shipped: add a new one.
import { PROCEDURES } from './procedures-data.js';
import { insertProcedure } from './seed.js';

const NOW = { sqlite: "(strftime('%Y-%m-%d %H:%M:%S','now'))", pg: "(to_char(now() at time zone 'utc','YYYY-MM-DD HH24:MI:SS'))" };
const ID = { sqlite: 'INTEGER PRIMARY KEY', pg: 'INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY' };

export const MIGRATIONS = [
  {
    id: '002_features',
    run: async (t, k) => {
      const sql = [
        // Paid plans expire; notification channel preferences.
        'ALTER TABLE users ADD COLUMN plan_expires_at TEXT',
        'ALTER TABLE users ADD COLUMN notify_push INTEGER NOT NULL DEFAULT 1',
        'ALTER TABLE users ADD COLUMN notify_whatsapp INTEGER NOT NULL DEFAULT 0',
        // Delivery outside the app (push / WhatsApp) happens once per notification.
        'ALTER TABLE notifications ADD COLUMN delivered_at TEXT',
        // Customer rating after a booking is done.
        'ALTER TABLE bookings ADD COLUMN rating INTEGER',
        "ALTER TABLE bookings ADD COLUMN review TEXT NOT NULL DEFAULT ''",
        `CREATE TABLE IF NOT EXISTS push_subscriptions (
          id ${ID[k]}, user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
          endpoint TEXT NOT NULL UNIQUE, p256dh TEXT NOT NULL, auth TEXT NOT NULL, created_at TEXT NOT NULL DEFAULT ${NOW[k]})`,
        `CREATE TABLE IF NOT EXISTS payments (
          id ${ID[k]}, user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
          plan TEXT NOT NULL, amount_kwd REAL NOT NULL, provider TEXT NOT NULL, reference TEXT NOT NULL UNIQUE,
          invoice_id TEXT, status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','paid','failed')),
          created_at TEXT NOT NULL DEFAULT ${NOW[k]}, paid_at TEXT)`,
        `CREATE TABLE IF NOT EXISTS reports (
          id ${ID[k]}, user_id INTEGER REFERENCES users(id) ON DELETE SET NULL,
          procedure_id INTEGER REFERENCES procedures(id) ON DELETE CASCADE, message TEXT NOT NULL,
          status TEXT NOT NULL DEFAULT 'open' CHECK (status IN ('open','resolved')), created_at TEXT NOT NULL DEFAULT ${NOW[k]})`,
        'CREATE INDEX IF NOT EXISTS idx_push_user ON push_subscriptions(user_id)',
        'CREATE INDEX IF NOT EXISTS idx_notif_delivery ON notifications(delivered_at)',
      ];
      for (const s of sql) await t.run(s);
    },
  },
  {
    // Health & insurance category: add its procedures to databases seeded before it existed.
    id: '003_health_procedures',
    run: async (t) => {
      for (const p of PROCEDURES.filter((x) => x.category === 'health')) {
        if (!(await t.get('SELECT 1 x FROM procedures WHERE slug=?', p.slug))) await insertProcedure(t, p);
      }
      await t.run(`UPDATE agents SET categories=? WHERE phone='96610205' AND categories=?`,
        JSON.stringify(['residency', 'civil', 'traffic', 'justice', 'health']), JSON.stringify(['residency', 'civil', 'traffic', 'justice']));
    },
  },
];

export async function migrate(t) {
  await t.run(`CREATE TABLE IF NOT EXISTS schema_migrations (id TEXT PRIMARY KEY, applied_at TEXT NOT NULL DEFAULT ${NOW[t.kind]})`);
  const done = new Set((await t.all('SELECT id FROM schema_migrations')).map((r) => r.id));
  for (const m of MIGRATIONS) {
    if (done.has(m.id)) continue;
    await m.run(t, t.kind);
    await t.run('INSERT INTO schema_migrations (id) VALUES (?)', m.id);
  }
}
