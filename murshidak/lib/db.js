// One async database API over two engines:
//   - Postgres (Supabase) when DATABASE_URL is set  → production
//   - built-in SQLite otherwise                     → local dev and tests
// SQL is written once with `?` placeholders and portable syntax (ON CONFLICT, CAST, etc.).
import fs from 'node:fs';
import path from 'node:path';

const nowSql = { sqlite: "(strftime('%Y-%m-%d %H:%M:%S','now'))", pg: "(to_char(now() at time zone 'utc','YYYY-MM-DD HH24:MI:SS'))" };
const idCol = { sqlite: 'INTEGER PRIMARY KEY', pg: 'INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY' };
const blob = { sqlite: 'BLOB', pg: 'BYTEA' };
const big = { sqlite: 'INTEGER', pg: 'BIGINT' };

function schema(k) {
  const NOW = nowSql[k], ID = idCol[k];
  return [
    `CREATE TABLE IF NOT EXISTS users (
      id ${ID}, phone TEXT NOT NULL UNIQUE, name TEXT NOT NULL DEFAULT '',
      role TEXT NOT NULL DEFAULT 'user' CHECK (role IN ('user','admin')),
      plan TEXT NOT NULL DEFAULT 'free' CHECK (plan IN ('free','family','business')),
      lang TEXT NOT NULL DEFAULT 'ar', created_at TEXT NOT NULL DEFAULT ${NOW})`,
    `CREATE TABLE IF NOT EXISTS otps (phone TEXT PRIMARY KEY, code_hash TEXT NOT NULL, expires_at ${big[k]} NOT NULL, attempts INTEGER NOT NULL DEFAULT 0)`,
    `CREATE TABLE IF NOT EXISTS sessions (token_hash TEXT PRIMARY KEY, user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE, expires_at ${big[k]} NOT NULL)`,
    `CREATE TABLE IF NOT EXISTS members (
      id ${ID}, user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE, name TEXT NOT NULL,
      relation TEXT NOT NULL CHECK (relation IN ('self','spouse','child','parent','domestic_worker','employee','other')),
      nationality TEXT NOT NULL DEFAULT '', created_at TEXT NOT NULL DEFAULT ${NOW})`,
    `CREATE TABLE IF NOT EXISTS documents (
      id ${ID}, user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
      member_id INTEGER NOT NULL REFERENCES members(id) ON DELETE CASCADE,
      type TEXT NOT NULL CHECK (type IN ('civil_id','passport','residency','driving_license','car_registration','other')),
      label TEXT NOT NULL DEFAULT '', number_enc TEXT, expiry_date TEXT NOT NULL, notes TEXT NOT NULL DEFAULT '',
      file_mime TEXT, created_at TEXT NOT NULL DEFAULT ${NOW})`,
    // Encrypted file bytes live apart from documents so lists never load them.
    `CREATE TABLE IF NOT EXISTS files (document_id INTEGER PRIMARY KEY REFERENCES documents(id) ON DELETE CASCADE, data ${blob[k]} NOT NULL)`,
    `CREATE TABLE IF NOT EXISTS procedures (
      id ${ID}, slug TEXT NOT NULL UNIQUE, category TEXT NOT NULL,
      mode TEXT NOT NULL CHECK (mode IN ('online','in_person','mixed')), popular INTEGER NOT NULL DEFAULT 0,
      title_ar TEXT NOT NULL, title_en TEXT NOT NULL, summary_ar TEXT NOT NULL DEFAULT '', summary_en TEXT NOT NULL DEFAULT '',
      fees_ar TEXT NOT NULL DEFAULT '', fees_en TEXT NOT NULL DEFAULT '', duration_ar TEXT NOT NULL DEFAULT '', duration_en TEXT NOT NULL DEFAULT '',
      keywords TEXT NOT NULL DEFAULT '{}', steps TEXT NOT NULL DEFAULT '[]', documents TEXT NOT NULL DEFAULT '[]',
      published INTEGER NOT NULL DEFAULT 1, updated_at TEXT NOT NULL DEFAULT ${NOW})`,
    `CREATE TABLE IF NOT EXISTS agents (
      id ${ID}, name_ar TEXT NOT NULL, name_en TEXT NOT NULL, phone TEXT NOT NULL,
      bio_ar TEXT NOT NULL DEFAULT '', bio_en TEXT NOT NULL DEFAULT '', categories TEXT NOT NULL DEFAULT '[]',
      areas_ar TEXT NOT NULL DEFAULT '', areas_en TEXT NOT NULL DEFAULT '', rating REAL NOT NULL DEFAULT 0,
      reviews INTEGER NOT NULL DEFAULT 0, price_kwd REAL NOT NULL, years INTEGER NOT NULL DEFAULT 0,
      status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','approved','rejected')),
      created_at TEXT NOT NULL DEFAULT ${NOW})`,
    `CREATE TABLE IF NOT EXISTS bookings (
      id ${ID}, user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
      agent_id INTEGER NOT NULL REFERENCES agents(id),
      procedure_id INTEGER REFERENCES procedures(id) ON DELETE SET NULL,
      member_id INTEGER REFERENCES members(id) ON DELETE SET NULL,
      status TEXT NOT NULL DEFAULT 'requested' CHECK (status IN ('requested','accepted','in_progress','done','cancelled')),
      preferred_date TEXT, notes TEXT NOT NULL DEFAULT '', price_kwd REAL NOT NULL, history TEXT NOT NULL DEFAULT '[]',
      created_at TEXT NOT NULL DEFAULT ${NOW}, updated_at TEXT NOT NULL DEFAULT ${NOW})`,
    `CREATE TABLE IF NOT EXISTS notifications (
      id ${ID}, user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE, dedupe_key TEXT UNIQUE,
      kind TEXT NOT NULL, title_ar TEXT NOT NULL, title_en TEXT NOT NULL, body_ar TEXT NOT NULL DEFAULT '', body_en TEXT NOT NULL DEFAULT '',
      link TEXT NOT NULL DEFAULT '', read INTEGER NOT NULL DEFAULT 0, created_at TEXT NOT NULL DEFAULT ${NOW})`,
    'CREATE INDEX IF NOT EXISTS idx_docs_user ON documents(user_id, expiry_date)',
    'CREATE INDEX IF NOT EXISTS idx_members_user ON members(user_id)',
    'CREATE INDEX IF NOT EXISTS idx_bookings_user ON bookings(user_id)',
    'CREATE INDEX IF NOT EXISTS idx_notif_user ON notifications(user_id, read)',
    'CREATE INDEX IF NOT EXISTS idx_sessions_user ON sessions(user_id)',
  ];
}

/** `?` → `$1, $2…` (no `?` appears inside string literals in this codebase). */
const toPg = (sql) => { let i = 0; return sql.replace(/\?/g, () => `$${++i}`); };
const isInsert = (sql) => /^\s*insert/i.test(sql) && !/returning/i.test(sql);

function sqliteApi(db) {
  const api = {
    kind: 'sqlite',
    async get(sql, ...p) { return db.prepare(sql).get(...p); },
    async all(sql, ...p) { return db.prepare(sql).all(...p); },
    async run(sql, ...p) { const r = db.prepare(sql).run(...p); return { changes: Number(r.changes), id: Number(r.lastInsertRowid) }; },
    async tx(fn) {
      db.exec('BEGIN');
      try { const r = await fn(api); db.exec('COMMIT'); return r; } catch (e) { db.exec('ROLLBACK'); throw e; }
    },
    async init(seed) {
      db.exec('PRAGMA journal_mode = WAL; PRAGMA foreign_keys = ON;');
      for (const s of schema('sqlite')) db.exec(s);
      await api.tx(seed);
    },
  };
  return api;
}

function pgApi(pool) {
  const wrapClient = (q) => ({
    kind: 'pg',
    async get(sql, ...p) { return (await q(toPg(sql), p)).rows[0]; },
    async all(sql, ...p) { return (await q(toPg(sql), p)).rows; },
    async run(sql, ...p) {
      // Tables without an id column are excluded; ON CONFLICT DO NOTHING simply returns no row.
      const r = await q(toPg(isInsert(sql) && !/^\s*insert into (otps|sessions|files|schema_migrations|agent_files)\b/i.test(sql) ? sql + ' RETURNING id' : sql), p);
      return { changes: r.rowCount, id: r.rows?.[0]?.id };
    },
  });
  const api = {
    ...wrapClient((s, p) => pool.query(s, p)),
    async tx(fn) {
      const c = await pool.connect();
      try {
        await c.query('BEGIN');
        const inner = wrapClient((s, p) => c.query(s, p));
        inner.tx = (f) => f(inner); // nested call joins the open transaction
        const r = await fn(inner);
        await c.query('COMMIT');
        return r;
      } catch (e) { await c.query('ROLLBACK').catch(() => {}); throw e; } finally { c.release(); }
    },
    async init(seed) {
      // Serialise schema creation and seeding across cold-starting instances.
      await api.tx(async (t) => {
        await t.run('SELECT pg_advisory_xact_lock(482190)');
        for (const s of schema('pg')) await t.run(s);
        await seed(t);
      });
    },
  };
  return api;
}

export async function openDb({ dataDir, databaseUrl }) {
  if (databaseUrl) {
    const { default: pg } = await import('pg');
    pg.types.setTypeParser(20, Number); // int8 → number (ids, timestamps in ms are < 2^53)
    pg.types.setTypeParser(700, Number); // float4 (rating, price)
    const pool = new pg.Pool({
      connectionString: databaseUrl.replace(/[?&]sslmode=[^&]*/, ''),
      // Supabase requires TLS (its pooler's certificate chain is not in Node's default store, so the
      // chain isn't verified). A local database without TLS: use localhost or add sslmode=disable.
      ssl: /sslmode=disable/.test(databaseUrl) || /@(localhost|127\.0\.0\.1)[:/]/.test(databaseUrl) ? false : { rejectUnauthorized: false },
      max: Number(process.env.PG_POOL_MAX || 3),
      idleTimeoutMillis: 10_000,
      connectionTimeoutMillis: 10_000,
    });
    return pgApi(pool);
  }
  const { DatabaseSync } = await import('node:sqlite');
  fs.mkdirSync(dataDir, { recursive: true });
  return sqliteApi(new DatabaseSync(path.join(dataDir, 'murshidak.db')));
}
